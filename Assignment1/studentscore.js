// A student scored:
// English = 75
// Mathematics = 82
// Computer Science = 91
// Create variables for the three scores.
// Calculate:
// * Total score
// * Average score

const english = 75;
const mathematics = 82;
const computerScience = 91;
const totalMarks = english + mathematics + computerScience;
const averageMarks = totalMarks / 3;
console.log("Total Marks:", totalMarks);
console.log("Average Marks:", averageMarks.toFixed(2));
